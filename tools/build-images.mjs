// Builds web-ready images + a manifest for the SAC gallery.
//
//   originals/story-01.jpg … story-14.jpg   (any of jpg/jpeg/png/webp/tif)
//        │
//        ▼  node tools/build-images.mjs   (run from the repo root, or `npm run images` inside /tools)
//   images/s01-640.webp, s01-1280.webp, s01-2048.webp …
//   images/manifest.js   →  window.SAC_IMAGES = { 1: { w, h, color, lqip, v:[{u,w,h}, …] }, … }
//
// Sizes are by LONG edge, so portrait and landscape files are handled alike.
// A size is skipped if it would upscale the original.

import sharp from 'sharp';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT   = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IN_DIR = path.join(ROOT, 'originals');
const OUT    = path.join(ROOT, 'images');

const LONG_EDGES = [640, 1280, 2048]; // grid (1x) · grid (2x) / modal · large screens
const QUALITY    = 78;                // WebP quality; ~100–300 KB per large size
const LQIP_EDGE  = 16;                // tiny blurred placeholder, inlined in the manifest
const ALIAS      = { 13: 1, 14: 2 };  // stories that reuse another story's art when no file of their own exists

const pad = (n) => String(n).padStart(2, '0');
const hex = ({ r, g, b }) => '#' + [r, g, b].map((c) => Math.round(c).toString(16).padStart(2, '0')).join('');
const kb  = (n) => (n / 1024).toFixed(0) + ' KB';

const files = (await fs.readdir(IN_DIR).catch(() => [])).filter((f) => /^story-\d+\.(jpe?g|png|webp|tiff?)$/i.test(f));
if (!files.length) {
  console.error(`No files like story-01.jpg found in ${IN_DIR}`);
  process.exit(1);
}

await fs.mkdir(OUT, { recursive: true });
for (const f of await fs.readdir(OUT)) if (/^s\d+-\d+\.webp$/.test(f)) await fs.unlink(path.join(OUT, f)); // clear stale variants

const manifest = {};
let total = 0;

for (const file of files.sort()) {
  const id   = parseInt(file.match(/\d+/)[0], 10);
  const src  = path.join(IN_DIR, file);
  const base = sharp(src).rotate();                       // honour EXIF orientation
  const meta = await sharp(await base.clone().toBuffer()).metadata();
  const { width: w, height: h } = meta;
  const long = Math.max(w, h);

  const edges = [...new Set(LONG_EDGES.map((e) => Math.min(e, long)))]; // never upscale; dedupe
  const v = [];
  for (const edge of edges) {
    const scale = edge / long;
    const vw = Math.round(w * scale), vh = Math.round(h * scale);
    const name = `s${pad(id)}-${edge}.webp`;
    const info = await base.clone().resize(vw, vh, { kernel: 'lanczos3' }).webp({ quality: QUALITY, effort: 5, smartSubsample: true }).toFile(path.join(OUT, name));
    v.push({ u: `images/${name}`, w: vw, h: vh });
    total += info.size;
    console.log(`  ${name.padEnd(16)} ${String(vw).padStart(4)}×${String(vh).padEnd(4)} ${kb(info.size)}`);
  }

  const { dominant } = await sharp(await base.clone().resize(64, 64, { fit: 'inside' }).toBuffer()).stats();
  const lqipBuf = await base.clone().resize({ width: w >= h ? LQIP_EDGE : undefined, height: h > w ? LQIP_EDGE : undefined }).webp({ quality: 40 }).toBuffer();

  manifest[id] = { w, h, color: hex(dominant), lqip: `data:image/webp;base64,${lqipBuf.toString('base64')}`, v };
  console.log(`story ${pad(id)}  ${w}×${h}  ${hex(dominant)}  placeholder ${lqipBuf.length} B\n`);
}

for (const [alias, target] of Object.entries(ALIAS)) {
  if (!manifest[alias] && manifest[target]) {
    manifest[alias] = manifest[target];
    console.log(`story ${pad(alias)} has no file → reuses story ${pad(target)}`);
  }
}

await fs.writeFile(
  path.join(OUT, 'manifest.js'),
  `// Generated by tools/build-images.mjs — do not edit by hand.\nwindow.SAC_IMAGES = ${JSON.stringify(manifest, null, 1)};\n`
);
console.log(`\nDone: ${Object.keys(manifest).length} stories, ${kb(total)} of WebP written to images/`);
